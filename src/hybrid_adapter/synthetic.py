"""Deterministic synthetic data generators.

*** ALL DATA PRODUCED HERE IS ARTIFICIAL. ***

Synthetic fixtures exist solely to verify dimensions, contracts, gradients,
checkpointing, and that the training loop can fit a known target function.
Their performance is NOT evidence of biological predictive accuracy.

Two generators are provided:

1. :func:`generate_whole_line_batch` — fixtures for the docx-spec adapter
   (whole-line response mode, M0).
2. :func:`generate_h7_batch` — fixtures whose generative process follows the
   H7 hypothesis: per-phase effects with a planted, phase-indexed mixing
   fraction alpha(k), context-specific phase compositions, and a
   composition-weighted whole-line response. Used to test the M1-M4 modes and
   the h7_validation package.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import torch

from .schemas import AdapterConfig

ARTIFICIAL_DATA_NOTICE = (
    "SYNTHETIC DATA: generated by hybrid_adapter.synthetic; artificial and not "
    "evidence of biological predictive accuracy."
)


@dataclass
class SyntheticConfig:
    n_contexts: int = 6
    n_perturbations: int = 8
    n_genes: int = 64
    batch_size: int = 4
    gears_dim: int = 32
    scgpt_dim: int = 512
    control_dim: int = 32
    seed: int = 0
    effect_units: str = "log2_fold_change"
    expression_units: str = "log1p_cpm"
    # H7 structure
    n_phases: int = 4
    phase_names: Tuple[str, ...] = ("G1", "S", "G2M", "M")
    planted_alpha: Optional[Tuple[float, ...]] = None  # defaults per phase
    noise_scale: float = 0.01
    # Systematic phase-dependent error in the statistical baseline. Without
    # this the baseline is nearly perfect and the M0-M4 ablation cannot
    # discriminate variants (all reach ~zero loss).
    stat_bias_scale: float = 0.3


def _generator(seed: int) -> torch.Generator:
    g = torch.Generator()
    g.manual_seed(int(seed))
    return g


def _ids(prefix: str, n: int) -> List[str]:
    return [f"{prefix}_{i:04d}" for i in range(n)]


# ---------------------------------------------------------------------------
# Whole-line (docx-spec) fixtures
# ---------------------------------------------------------------------------
def generate_whole_line_batch(
    config: Optional[SyntheticConfig] = None,
    include_gears: bool = True,
    include_target: bool = True,
    seed_offset: int = 0,
) -> Dict[str, Any]:
    """Generate one validated-shape synthetic batch for whole-line mode.

    The planted target function is a smooth, learnable function of quantities
    the adapter actually observes (basal expression, stat effect, and latent
    factors encoded in the control features and embeddings):

        residual_true = 0.5 * tanh(stat) * basal + 0.1 * u_c * v_g

    where ``u_c`` is recoverable from control features and ``v_g`` from the
    scGPT response-gene embeddings. ``target_effects = stat + residual_true``.
    """
    cfg = config or SyntheticConfig()
    g = _generator(cfg.seed + seed_offset)
    B, G = cfg.batch_size, cfg.n_genes

    u_c = torch.randn(cfg.n_contexts, cfg.control_dim, generator=g)
    v_g = torch.randn(cfg.n_genes, cfg.scgpt_dim, generator=g) * 0.05
    pert_emb = torch.randn(cfg.n_perturbations, cfg.gears_dim, generator=g) * 0.05

    ctx_idx = torch.randint(0, cfg.n_contexts, (B,), generator=g)
    pert_idx = torch.randint(0, cfg.n_perturbations, (B,), generator=g)

    control_features = u_c[ctx_idx]
    scgpt_target = torch.randn(B, cfg.scgpt_dim, generator=g) * 0.05
    scgpt_response = v_g.unsqueeze(0).expand(B, G, cfg.scgpt_dim).clone()
    basal = torch.rand(B, G, generator=g) * 2.0 + 0.1
    stat = torch.randn(B, G, generator=g) * 0.5

    batch: Dict[str, Any] = {
        "context_ids": [f"ctx_{int(i)}" for i in ctx_idx],
        "perturbation_ids": [f"pert_{int(i)}" for i in pert_idx],
        "response_gene_ids": _ids("gene", G),
        "stat_effects": stat,
        "scgpt_target_embeddings": scgpt_target,
        "scgpt_response_embeddings": scgpt_response,
        "control_features": control_features,
        "control_gene_expression": basal,
        "effect_units": cfg.effect_units,
        "expression_units": cfg.expression_units,
        "availability_masks": {
            "gears_effects": include_gears,
            "gears_embeddings": include_gears,
            "scgpt_target": True,
            "scgpt_response": True,
            "control_features": True,
        },
    }
    if include_gears:
        batch["gears_effects"] = torch.randn(B, G, generator=g) * 0.3
        batch["gears_embeddings"] = pert_emb[pert_idx]

    if include_target:
        u = control_features[:, 0]
        v = scgpt_response[:, :, 0]
        residual_true = 0.5 * torch.tanh(stat) * basal + 0.1 * u.unsqueeze(1) * v
        batch["target_effects"] = stat + residual_true

    batch["artificial"] = ARTIFICIAL_DATA_NOTICE
    return batch


def make_synthetic_loaders(
    config: Optional[SyntheticConfig] = None,
    n_train_batches: int = 8,
    n_val_batches: int = 2,
    include_gears: bool = True,
):
    """Simple list-based train/validation loaders of synthetic batches."""
    cfg = config or SyntheticConfig()
    train = [
        generate_whole_line_batch(cfg, include_gears=include_gears, seed_offset=1000 + i)
        for i in range(n_train_batches)
    ]
    val = [
        generate_whole_line_batch(cfg, include_gears=include_gears, seed_offset=2000 + i)
        for i in range(n_val_batches)
    ]
    return train, val


# ---------------------------------------------------------------------------
# H7-structured fixtures
# ---------------------------------------------------------------------------
def generate_h7_batch(
    config: Optional[SyntheticConfig] = None,
    include_gears: bool = False,
    seed_offset: int = 0,
) -> Dict[str, Any]:
    """Generate a synthetic batch whose generative process follows H7.

    Generative process (all artificial):

    * Each context c has a phase composition ``p_c`` (Dirichlet, K phases).
    * A shared invariant component ``I(g,k,j)`` and context-specific dependent
      components ``D_c(g,k,j)`` are drawn once per generator seed.
    * True per-phase effect: ``Delta(c,g,k,j) = a(k) * I + (1 - a(k)) * D_c``
      with planted ``a(k)`` in (0, 1).
    * The statistical baseline is the true effect plus small noise.
    * Whole-line truth: ``target = sum_k p_c(k) * Delta(c,g,k,j)``.
    * ``compsim_weights`` are computed as ``1 - TV(p_c, p_ref)`` against a
      reference composition (uniform), matching the M4 gate definition.
    """
    cfg = config or SyntheticConfig()
    g = _generator(cfg.seed + seed_offset)
    B, G, K = cfg.batch_size, cfg.n_genes, cfg.n_phases

    alpha = (
        torch.tensor(cfg.planted_alpha, dtype=torch.float32)
        if cfg.planted_alpha is not None
        else torch.linspace(0.2, 0.9, K)
    )
    assert alpha.shape[0] == K

    # Compositions: Dirichlet-like via normalised exponential of uniforms.
    logits_p = torch.rand(B, K, generator=g) * 2.0
    proportions = torch.softmax(logits_p, dim=-1)

    invariant = torch.randn(1, K, G, generator=g) * 0.5
    dependent = torch.randn(B, K, G, generator=g) * 0.5
    true_phase = alpha.view(1, K, 1) * invariant + (1 - alpha.view(1, K, 1)) * dependent
    # Statistical baseline: true per-phase effect + phase-dependent systematic
    # bias + small noise. The bias is what the residual correction must learn.
    phase_bias = torch.randn(K, G, generator=g) * cfg.stat_bias_scale
    stat_phase = true_phase + phase_bias.unsqueeze(0) \
        + torch.randn(B, K, G, generator=g) * cfg.noise_scale
    stat_line = (proportions.unsqueeze(-1) * stat_phase).sum(dim=1)
    target = (proportions.unsqueeze(-1) * true_phase).sum(dim=1)

    ref = torch.full((K,), 1.0 / K)
    # Per-phase composition similarity: TV between the binary partition
    # {phase k vs rest} of p_c and of the reference, which reduces to
    # |p_c(k) - p_ref(k)|. Shape [B, K], values in [0, 1].
    compsim = (1.0 - (proportions - ref.unsqueeze(0)).abs()).clamp(0.0, 1.0)

    ctx_idx = torch.arange(B) % cfg.n_contexts
    pert_idx = torch.randint(0, cfg.n_perturbations, (B,), generator=g)

    batch: Dict[str, Any] = {
        "context_ids": [f"ctx_{int(i)}" for i in ctx_idx],
        "perturbation_ids": [f"pert_{int(i)}" for i in pert_idx],
        "response_gene_ids": _ids("gene", G),
        "stat_effects": stat_line,
        "scgpt_target_embeddings": torch.randn(B, cfg.scgpt_dim, generator=g) * 0.05,
        "scgpt_response_embeddings": (
            torch.randn(cfg.n_genes, cfg.scgpt_dim, generator=g) * 0.05
        ).unsqueeze(0).expand(B, G, cfg.scgpt_dim).clone(),
        "control_features": torch.randn(B, cfg.control_dim, generator=g),
        "control_gene_expression": torch.rand(B, G, generator=g) * 2.0 + 0.1,
        "effect_units": cfg.effect_units,
        "expression_units": cfg.expression_units,
        "availability_masks": {
            "gears_effects": include_gears,
            "gears_embeddings": include_gears,
            "scgpt_target": True,
            "scgpt_response": True,
            "control_features": True,
        },
        # H7 fields
        "phase_proportions": proportions,
        "phase_stat_effects": stat_phase,
        "phase_labels": list(cfg.phase_names[:K]),
        "compsim_weights": compsim,
        "target_effects": target,
        "ground_truth_alpha": alpha,
        "artificial": ARTIFICIAL_DATA_NOTICE,
    }
    if include_gears:
        batch["gears_effects"] = torch.randn(B, G, generator=g) * 0.3
        batch["gears_embeddings"] = torch.randn(B, cfg.gears_dim, generator=g) * 0.05
    return batch


def make_h7_loaders(
    config: Optional[SyntheticConfig] = None,
    n_train_batches: int = 8,
    n_val_batches: int = 2,
):
    """Train/validation loaders of H7-structured synthetic batches."""
    cfg = config or SyntheticConfig()
    train = [generate_h7_batch(cfg, seed_offset=3000 + i) for i in range(n_train_batches)]
    val = [generate_h7_batch(cfg, seed_offset=4000 + i) for i in range(n_val_batches)]
    return train, val
